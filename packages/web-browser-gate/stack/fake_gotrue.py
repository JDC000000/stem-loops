"""Fake GoTrue (Supabase Auth) on 127.0.0.1:54321 — LOCAL TEST ONLY.

Stateless: access tokens are HS256 JWTs signed with a local secret ($STACK_STATE/gotrue_secret, generated by up.sh).
GET /auth/v1/user verifies the signature + exp and returns a user built from the claims.
Implements just enough for @supabase/ssr createServerClient().auth.getUser():
  GET  /auth/v1/user                       -> user | 401
  POST /auth/v1/token?grant_type=refresh_token -> new session (refresh_token = the access token)
  POST /auth/v1/logout                     -> 204
  DELETE /auth/v1/admin/users/<id>         -> 200 (admin delete, used by account deletion)
  GET  /auth/v1/health                     -> 200
Anything else -> 404 JSON, logged.
"""
import base64, hashlib, hmac, json, os, sys, time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlsplit, parse_qs

HOST, PORT = "127.0.0.1", int(os.environ.get("GOTRUE_PORT", "54321"))
SECRET = open(os.environ["GOTRUE_SECRET_FILE"], "rb").read().strip()

def b64u(b): return base64.urlsafe_b64encode(b).rstrip(b"=").decode()
def b64u_dec(s): return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))

def sign(claims):
    h = b64u(json.dumps({"alg": "HS256", "typ": "JWT"}).encode())
    p = b64u(json.dumps(claims).encode())
    sig = b64u(hmac.new(SECRET, f"{h}.{p}".encode(), hashlib.sha256).digest())
    return f"{h}.{p}.{sig}"

def verify(tok):
    try:
        h, p, s = tok.split(".")
        exp_sig = b64u(hmac.new(SECRET, f"{h}.{p}".encode(), hashlib.sha256).digest())
        if not hmac.compare_digest(exp_sig, s):
            return None
        c = json.loads(b64u_dec(p))
        if c.get("exp", 0) < time.time():
            return None
        return c
    except Exception:
        return None

def user_from(c):
    return {"id": c["sub"], "aud": "authenticated", "role": "authenticated", "email": c.get("email"),
            "email_confirmed_at": "2026-01-01T00:00:00Z", "phone": "", "app_metadata": {"provider": "email", "providers": ["email"]},
            "user_metadata": c.get("user_metadata", {}), "identities": [], "created_at": "2026-01-01T00:00:00Z",
            "updated_at": "2026-01-01T00:00:00Z", "is_anonymous": False}

def session_for(c):
    now = int(time.time()); exp = now + 86400 * 7
    claims = dict(c, iat=now, exp=exp)
    tok = sign(claims)
    return {"access_token": tok, "token_type": "bearer", "expires_in": exp - now, "expires_at": exp,
            "refresh_token": tok, "user": user_from(claims)}

class H(BaseHTTPRequestHandler):
    def _send(self, code, obj=None):
        body = b"" if obj is None else json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self._cors()
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
    def _cors(self):
        o = self.headers.get("Origin")
        if o and o.startswith(("http://127.0.0.1:", "http://localhost:")):
            self.send_header("Access-Control-Allow-Origin", o)
            self.send_header("Access-Control-Allow-Credentials", "true")
            self.send_header("Access-Control-Allow-Headers", "authorization, apikey, content-type, x-client-info, x-supabase-api-version")
            self.send_header("Access-Control-Allow-Methods", "GET, POST, DELETE, OPTIONS")
    def do_OPTIONS(self):
        self.send_response(204); self._cors(); self.send_header("Content-Length", "0"); self.end_headers()
    def _claims(self):
        a = self.headers.get("Authorization", "")
        return verify(a[7:]) if a.lower().startswith("bearer ") else None
    def log_message(self, fmt, *a):
        sys.stderr.write("gotrue %s %s\n" % (self.command, self.path)); sys.stderr.flush()
    def do_GET(self):
        path = urlsplit(self.path).path
        if path == "/auth/v1/health": return self._send(200, {"name": "fake-gotrue", "loopback": True})
        if path == "/auth/v1/user":
            c = self._claims()
            if not c: return self._send(401, {"code": 401, "error_code": "bad_jwt", "msg": "invalid JWT"})
            return self._send(200, user_from(c))
        if path == "/auth/v1/settings": return self._send(200, {"external": {"email": True}, "disable_signup": False})
        self._send(404, {"code": 404, "msg": f"fake-gotrue: {path} not implemented"})
    def do_POST(self):
        u = urlsplit(self.path); q = parse_qs(u.query)
        n = int(self.headers.get("Content-Length") or 0); body = self.rfile.read(n) if n else b""
        if u.path == "/auth/v1/token" and q.get("grant_type") == ["refresh_token"]:
            try: rt = json.loads(body or b"{}").get("refresh_token", "")
            except Exception: rt = ""
            c = verify(rt)
            if not c: return self._send(400, {"code": 400, "error_code": "refresh_token_not_found", "msg": "Invalid Refresh Token"})
            return self._send(200, session_for(c))
        if u.path == "/auth/v1/logout": return self._send(204)
        self._send(404, {"code": 404, "msg": f"fake-gotrue: POST {u.path} not implemented"})
    def do_DELETE(self):
        if urlsplit(self.path).path.startswith("/auth/v1/admin/users/"): return self._send(200, {})
        self._send(404, {"code": 404})

